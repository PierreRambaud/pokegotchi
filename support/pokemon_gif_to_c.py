#!/usr/bin/env python3
"""
Convert the Pokemon GIFs of assets_source/pokemon into C arrays for lv_gif.

The decoder of LVGL 9.4 (AnimatedGIF) applies the "restore to background"
disposal of a frame while drawing that same frame: a small patch frame, like
the eyes closing, then erases everything around it. The original GIFs are full
of such patches, so the Pokemon seemed to blink. Every frame is rebuilt here as
a whole image (ImageMagick -coalesce), which the decoder draws correctly.

Usage: support/pokemon_gif_to_c.py [output directory]
Requires ImageMagick (magick or convert).
"""

import glob
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "assets_source", "pokemon")


def magick_command():
    for name in ("magick", "convert"):
        path = shutil.which(name)
        if path:
            return [path]
    sys.exit("ImageMagick is required (magick or convert)")


def full_frames(magick, source):
    with tempfile.TemporaryDirectory() as tmp:
        target = os.path.join(tmp, "out.gif")
        subprocess.run(magick + [source, "-coalesce", "-set", "dispose", "Background", target], check=True)
        with open(target, "rb") as f:
            return f.read()


def write_c(path, name, data):
    attribute = "LV_ATTRIBUTE_IMG_" + name.upper()
    lines = [
        "#ifdef LV_LVGL_H_INCLUDE_SIMPLE",
        '#include "lvgl.h"',
        "#else",
        '#include "lvgl/lvgl.h"',
        "#endif",
        "",
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN",
        "#define LV_ATTRIBUTE_MEM_ALIGN",
        "#endif",
        "#ifndef " + attribute,
        "#define " + attribute,
        "#endif",
        "// Generated by support/pokemon_gif_to_c.py: every frame is a whole image",
        "const LV_ATTRIBUTE_MEM_ALIGN %s uint8_t %s_map[] = {" % (attribute, name),
    ]
    for i in range(0, len(data), 13):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i : i + 13]) + ",")
    lines += [
        "};",
        "",
        "const lv_image_dsc_t %s = {" % name,
        "  .header.magic = LV_IMAGE_HEADER_MAGIC,",
        "  .header.cf = LV_COLOR_FORMAT_RAW,",
        "  .header.flags = 0,",
        "  .header.w = 0,",
        "  .header.h = 0,",
        "  .header.stride = 0,",
        "  .data_size = sizeof(%s_map)," % name,
        "  .data = %s_map," % name,
        "};",
        "",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    output = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "src", "assets", "pokemon")
    magick = magick_command()

    sources = []
    for path in sorted(glob.glob(os.path.join(SOURCE, "pokemon_*.gif"))):
        sources.append((path, os.path.splitext(os.path.basename(path))[0]))
    for path in sorted(glob.glob(os.path.join(SOURCE, "sick", "*.gif"))):
        sources.append((path, "pokemon_sick_" + os.path.splitext(os.path.basename(path))[0]))

    for path, name in sources:
        data = full_frames(magick, path)
        write_c(os.path.join(output, name + ".c"), name, data)
        print("%s: %d bytes" % (name, len(data)))


if __name__ == "__main__":
    main()
